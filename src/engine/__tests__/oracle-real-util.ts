import { spawnSync } from 'node:child_process';
import type { Database, RawValue, TableDef, Value } from '../types';

/**
 * Đồ dùng cho `oracle-real.test.ts`: nói chuyện với Oracle thật qua `docker exec` + sqlplus.
 * Mật khẩu đọc từ biến môi trường `ORA_PW`, không ghi vào repo. Tên container: `ORACLE_CONTAINER` (mặc định `oraxe`).
 * Cách dựng container: xem `docs/dialect-verification.md`, mục Oracle.
 */

const CONTAINER = process.env.ORACLE_CONTAINER ?? 'oraxe';
const USER = process.env.ORA_USER ?? 'hoc';
const SERVICE = process.env.ORA_SERVICE ?? 'XEPDB1';

const HEADER = [
  'SET ECHO OFF FEEDBACK OFF VERIFY OFF DEFINE OFF HEADING ON PAGESIZE 50000 LINESIZE 32767 LONG 100000 NUMWIDTH 40 TAB OFF TRIMSPOOL ON SQLBLANKLINES ON',
  "ALTER SESSION SET NLS_DATE_FORMAT = 'YYYY-MM-DD HH24:MI:SS';",
  'WHENEVER SQLERROR CONTINUE',
  'SET MARKUP CSV ON DELIMITER , QUOTE ON',
].join('\n');

/** Chạy một đoạn script trong sqlplus, trả về toàn bộ output. */
export function sqlplus(script: string): string {
  const pw = process.env.ORA_PW;
  if (!pw) throw new Error('thiếu biến môi trường ORA_PW');
  const r = spawnSync('docker', ['exec', '-i', '-e', 'NLS_LANG=AMERICAN_AMERICA.AL32UTF8', CONTAINER, 'sqlplus', '-s', '/nolog'], {
    input: `CONNECT ${USER}/${pw}@${SERVICE}\n${HEADER}\n${script}\nEXIT\n`,
    encoding: 'utf8',
    maxBuffer: 512 * 1024 * 1024,
    timeout: 600_000,
  });
  if (r.error) throw r.error;
  return r.stdout;
}

/** Xóa mọi view, table, sequence của user. */
export const CLEAN = `BEGIN
  FOR r IN (SELECT view_name n FROM user_views) LOOP EXECUTE IMMEDIATE 'DROP VIEW "' || r.n || '"'; END LOOP;
  FOR r IN (SELECT table_name n FROM user_tables) LOOP EXECUTE IMMEDIATE 'DROP TABLE "' || r.n || '" CASCADE CONSTRAINTS PURGE'; END LOOP;
  FOR r IN (SELECT sequence_name n FROM user_sequences WHERE sequence_name NOT LIKE 'ISEQ$$%') LOOP EXECUTE IMMEDIATE 'DROP SEQUENCE "' || r.n || '"'; END LOOP;
END;
/`;

const lit = (v: RawValue, type: string): string => {
  if (v === null) return 'NULL';
  if (type === 'date') return `TO_DATE('${v}', 'YYYY-MM-DD')`;
  if (type === 'datetime') return `TO_DATE('${v}', 'YYYY-MM-DD HH24:MI:SS')`;
  if (typeof v === 'number') return String(v);
  return `'${v.replace(/'/g, "''")}'`;
};

/** Đổi một table mẫu thành DDL và INSERT của Oracle. Foreign key và CHECK thêm sau khi nạp xong. */
export function tableToOracle(t: TableDef): { create: string; inserts: string[]; after: string[] } {
  const cols = t.columns.map((c) => {
    let ty: string;
    if (c.type === 'text') ty = `VARCHAR2(${c.length ?? 1000} CHAR)`;
    else if (c.type === 'date' || c.type === 'datetime') ty = 'DATE';
    else if (c.precision !== undefined) ty = `NUMBER(${c.precision}${c.scale !== undefined ? `, ${c.scale}` : ''})`;
    else ty = 'NUMBER';
    const ident = c.identity ? ' GENERATED BY DEFAULT AS IDENTITY' : '';
    return `${c.name} ${ty}${ident}${c.notNull && !c.pk ? ' NOT NULL' : ''}`;
  });
  const pk = t.columns.filter((c) => c.pk).map((c) => c.name);
  if (pk.length) cols.push(`PRIMARY KEY (${pk.join(', ')})`);
  for (const c of t.columns) if (c.unique) cols.push(`UNIQUE (${c.name})`);
  const inserts = t.rows.map((r) => `INSERT INTO ${t.name} VALUES (${r.map((v, i) => lit(v, t.columns[i].type)).join(', ')});`);
  const after: string[] = [];
  for (const c of t.columns) {
    if (c.fk) after.push(`ALTER TABLE ${t.name} ADD FOREIGN KEY (${c.name}) REFERENCES ${c.fk.table}(${c.fk.column});`);
    if (c.identity) after.push(`ALTER TABLE ${t.name} MODIFY (${c.name} GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE));`);
  }
  for (const ch of t.checks ?? []) after.push(`ALTER TABLE ${t.name} ADD CHECK (${ch});`);
  return { create: `CREATE TABLE ${t.name} (\n  ${cols.join(',\n  ')}\n);`, inserts, after };
}

/** Script nạp cả database mẫu: dọn sạch, tạo table, nạp row, thêm foreign key và CHECK. */
export function loadScript(db: Database): string {
  const parts = db.tables.map(tableToOracle);
  return [CLEAN, ...parts.map((p) => p.create), ...parts.flatMap((p) => p.inserts), ...parts.flatMap((p) => p.after), 'COMMIT;'].join('\n');
}

export interface OraResult {
  /** Mã lỗi dạng 'ORA-00942', hoặc undefined nếu chạy được. */
  code?: string;
  message?: string;
  columns: string[];
  rows: (string | null)[][];
}

function parseCsv(text: string): string[][] {
  const out: string[][] = [];
  let row: string[] = [];
  let cur = '';
  let inQ = false;
  let started = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (inQ) {
      if (ch === '"') {
        if (text[i + 1] === '"') {
          cur += '"';
          i++;
        } else inQ = false;
      } else cur += ch;
    } else if (ch === '"') {
      inQ = true;
      started = true;
    } else if (ch === ',') {
      row.push(cur);
      cur = '';
      started = true;
    } else if (ch === '\n') {
      if (started || cur !== '') row.push(cur);
      if (row.length) out.push(row);
      row = [];
      cur = '';
      started = false;
    } else if (ch !== '\r') {
      cur += ch;
      started = true;
    }
  }
  if (started || cur !== '') row.push(cur);
  if (row.length) out.push(row);
  return out;
}

/**
 * Chạy nhiều lệnh một lượt. Mỗi lệnh ra một OraResult: lỗi thì có `code`, SELECT thì có `columns` và `rows`.
 * Chuỗi rỗng đọc là NULL (Oracle coi '' là NULL).
 */
export function runMany(statements: string[], prelude = ''): OraResult[] {
  const script = statements.map((s, i) => `PROMPT @@BEGIN ${i}\n${s.trim().replace(/;\s*$/, '')}${/\n\/\s*$/.test(s) ? '' : ';'}\nPROMPT @@END`).join('\n');
  const out = sqlplus(`${prelude}\n${script}`);
  const res: OraResult[] = [];
  const re = /@@BEGIN (\d+)\r?\n([\s\S]*?)@@END/g;
  for (let m = re.exec(out); m; m = re.exec(out)) {
    const body = m[2];
    const err = /^((?:ORA|SP2|PLS)-\d{4,5}): (.*)$/m.exec(body);
    if (err) res.push({ code: err[1], message: err[2], columns: [], rows: [] });
    else {
      const table = parseCsv(body);
      const header = table.shift() ?? [];
      res.push({ columns: header, rows: table.map((r) => r.map((c) => (c === '' ? null : c))) });
    }
  }
  if (res.length !== statements.length) throw new Error(`sqlplus trả ${res.length} kết quả cho ${statements.length} lệnh`);
  return res;
}

/** Chạy một lệnh. */
export const runOne = (sql: string, prelude = ''): OraResult => runMany([sql], prelude)[0];

/** Nạp database mẫu vào schema thật, ném lỗi nếu có lệnh nào hỏng. */
export function load(db: Database): void {
  const out = sqlplus(loadScript(db));
  const bad = out.split('\n').filter((l) => /^(ORA|SP2|PLS)-\d+/.test(l));
  if (bad.length) throw new Error(`nạp ${db.name} lỗi: ${bad.slice(0, 3).join(' | ')}`);
}

/* ---------- so kết quả ---------- */

export type Cell = string | null;

/** Giá trị của engine về chuỗi so được. Số bỏ số 0 ở đuôi, ngày về YYYY-MM-DD (bỏ giờ 00:00:00). */
export function normValue(v: Value | Uint8Array | string | null): Cell {
  if (v === null || v === undefined) return null;
  if (typeof v === 'object' && 'kind' in v) return normText(v.iso);
  if (typeof v === 'boolean') return v ? '1' : '0';
  return normText(String(v));
}

export function normText(s: string): string {
  const t = s.replace(/ 00:00:00$/, '');
  if (/^-?(\d+\.?\d*|\.\d+)([eE][+-]?\d+)?$/.test(t) && !/^-?0\d/.test(t)) {
    const n = Number(t);
    if (Number.isFinite(n)) return String(Number(n.toPrecision(12)));
  }
  return t;
}

export const normOra = (c: string | null): Cell => (c === null ? null : normText(c));

/** So hai tập row. `ordered` false thì so như tập. Trả mô tả lệch, hoặc null nếu khớp. */
export function diffRows(eng: Cell[][], ora: Cell[][], ordered: boolean): string | null {
  const key = (r: Cell[]) => JSON.stringify(r);
  const a = eng.map(key);
  const b = ora.map(key);
  if (!ordered) {
    a.sort();
    b.sort();
  }
  if (a.length !== b.length) return `số row: engine ${a.length}, Oracle ${b.length}`;
  for (let i = 0; i < a.length; i++) if (a[i] !== b[i]) return `row ${i}: engine ${a[i]}, Oracle ${b[i]}`;
  return null;
}
