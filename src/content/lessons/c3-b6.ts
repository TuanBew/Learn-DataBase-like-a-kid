const empMysql = `CREATE TABLE employees (
  employee_id INT AUTO_INCREMENT PRIMARY KEY,
  full_name VARCHAR(100) NOT NULL,
  email VARCHAR(100) NOT NULL UNIQUE,
  hire_date DATE NOT NULL,
  salary DECIMAL(12,2) NOT NULL CHECK (salary > 0),
  department_id INT,
  manager_id INT,
  CONSTRAINT fk_employees_department
    FOREIGN KEY (department_id) REFERENCES departments (department_id),
  CONSTRAINT fk_employees_manager
    FOREIGN KEY (manager_id) REFERENCES employees (employee_id)
);`;

const empOracle = `CREATE TABLE employees (
  employee_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR2(100) NOT NULL,
  email VARCHAR2(100) NOT NULL UNIQUE,
  hire_date DATE NOT NULL,
  salary NUMBER(12,2) NOT NULL CHECK (salary > 0),
  department_id NUMBER,
  manager_id NUMBER,
  CONSTRAINT fk_employees_department
    FOREIGN KEY (department_id) REFERENCES departments (department_id),
  CONSTRAINT fk_employees_manager
    FOREIGN KEY (manager_id) REFERENCES employees (employee_id)
)`;

const insM = (name: string, email: string, date: string, dept: number, mgr: string) =>
  `INSERT INTO employees (full_name, email, hire_date, salary, department_id, manager_id)\nVALUES ('${name}', '${email}', '${date}', 18000000, ${dept}, ${mgr});`;
const insO = (name: string, email: string, date: string, dept: number, mgr: string) =>
  `INSERT INTO employees (full_name, email, hire_date, salary, department_id, manager_id)\nVALUES ('${name}', '${email}', DATE '${date}', 18000000, ${dept}, ${mgr});`;

