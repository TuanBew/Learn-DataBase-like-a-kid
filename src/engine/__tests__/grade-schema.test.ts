import { describe, expect, it } from 'vitest';
import { gradeSchema } from '../index';
import type { Dialect, SchemaSpec } from '../index';
import { BOTH, S } from './ddl-util';

/** Máy chấm bài dựng table. Database của người học dựng bằng DDL thật, rồi chấm theo SchemaSpec. */

const SPEC: SchemaSpec = {
  tables: [
    {
      name: 'customers',
      columns: [
        { name: 'id', type: 'int', pk: true, identity: true, label: 'id là primary key, tự tăng' },
        { name: 'name', type: 'text', minLength: 50, notNull: true, label: 'name là chữ dài từ 50, không NULL' },
        { name: 'email', type: 'text', unique: true, label: 'email không trùng nhau' },
        { name: 'city', type: 'text', default: 'Hue', label: 'city mặc định Hue' },
        { name: 'score', type: ['int', 'decimal'], default: 0, label: 'score là số, mặc định 0' },
      ],
    },
    {
      name: 'orders',
      columns: [
        { name: 'id', type: 'int', pk: true, label: 'id là primary key' },
        { name: 'customer_id', type: 'int', fk: { table: 'customers', column: 'id', onDelete: 'cascade' }, label: 'customer_id trỏ tới customers, xóa theo' },
      ],
    },
  ],
};

const DDL: Record<Dialect, string[]> = {
  mysql: [
    "CREATE TABLE customers (id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(60) NOT NULL, email VARCHAR(80) UNIQUE, city VARCHAR(20) DEFAULT 'Hue', score INT DEFAULT 0)",
    'CREATE TABLE orders (id INT PRIMARY KEY, customer_id INT, FOREIGN KEY (customer_id) REFERENCES customers(id) ON DELETE CASCADE)',
  ],
  oracle: [
    "CREATE TABLE customers (id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR2(60) NOT NULL, email VARCHAR2(80) UNIQUE, city VARCHAR2(20) DEFAULT 'Hue', score NUMBER DEFAULT 0)",
    'CREATE TABLE orders (id NUMBER(10) PRIMARY KEY, customer_id NUMBER(10), CONSTRAINT o_fk FOREIGN KEY (customer_id) REFERENCES customers(id) ON DELETE CASCADE)',
  ],
};

const build = (d: Dialect, steps: string[] = DDL[d]) => {
  const s = S(d);
  // Câu DDL lỗi thì không để lại gì, như người học gặp lỗi.
  for (const x of steps) s.run(x);
  return s;
};
const grade = (d: Dialect, steps?: string[], spec = SPEC) => gradeSchema(build(d, steps).db(), spec, d);
const failed = (r: ReturnType<typeof grade>) => r.checks.filter((c) => !c.ok).map((c) => c.id);

describe('gradeSchema: bài làm đúng', () => {
  for (const d of BOTH) {
    it(`${d}: đúng hết, mỗi table một check, mỗi column một check, mỗi table một check column thừa`, () => {
      const r = grade(d);
      expect(failed(r)).toEqual([]);
      expect(r.ok).toBe(true);
      expect(r.checks.map((c) => c.id)).toEqual([
        'table:customers',
        'customers.id',
        'customers.name',
        'customers.email',
        'customers.city',
        'customers.score',
        'customers:extra',
        'table:orders',
        'orders.id',
        'orders.customer_id',
        'orders:extra',
      ]);
      expect(r.checks[1].label).toBe('id là primary key, tự tăng');
    });
  }

  it('không đụng database gốc', () => {
    const s = build('mysql');
    const before = JSON.stringify(s.db());
    gradeSchema(s.db(), { tables: [], probes: [{ id: 'p', label: 'p', sql: { mysql: 'DROP TABLE orders' }, expect: 'ok' }] }, 'mysql');
    expect(JSON.stringify(s.db())).toBe(before);
  });

  it('tên table và column không phân biệt hoa thường', () => {
    const r = gradeSchema(build('mysql').db(), { tables: [{ name: 'CUSTOMERS', columns: [{ name: 'ID', type: 'int', pk: true, label: 'x' }], allowExtra: true }] }, 'mysql');
    expect(r.ok).toBe(true);
  });
});

describe('gradeSchema: bài làm sai', () => {
  it('thiếu table: check table sai, các column của nó sai theo', () => {
    const r = grade('mysql', [DDL.mysql[0]]);
    expect(failed(r)).toEqual(['table:orders', 'orders.id', 'orders.customer_id', 'orders:extra']);
    expect(r.checks.find((c) => c.id === 'table:orders')?.note).toBe('Chưa có table này.');
    expect(r.ok).toBe(false);
  });

  it('thiếu column', () => {
    const r = grade('oracle', [DDL.oracle[0].replace(', city VARCHAR2(20) DEFAULT \'Hue\'', ''), DDL.oracle[1]]);
    expect(failed(r)).toEqual(['customers.city']);
    expect(r.checks.find((c) => c.id === 'customers.city')?.note).toBe('Chưa có column city.');
  });

  it('sai nhóm data type: nói data type đang dùng và nhóm cần', () => {
    const r = grade('mysql', [DDL.mysql[0].replace('score INT', 'score VARCHAR(5)'), DDL.mysql[1]]);
    expect(failed(r)).toEqual(['customers.score']);
    expect(r.checks.find((c) => c.id === 'customers.score')?.note).toContain('VARCHAR(5)');
  });

  it('nhóm data type: nhận cả hai nhóm trong danh sách, và Oracle NUMBER(p) tính là số nguyên', () => {
    expect(grade('oracle').ok).toBe(true);
    const r = grade('oracle', [DDL.oracle[0].replace('id NUMBER(10)', 'id VARCHAR2(10)').replace(' GENERATED BY DEFAULT AS IDENTITY', ''), DDL.oracle[1]]);
    expect(failed(r)).toContain('customers.id');
    // orders không dựng được vì foreign key không hợp với column id mới.
    expect(failed(r)).toContain('table:orders');
  });

  it('độ dài ngắn hơn minLength', () => {
    const r = grade('mysql', [DDL.mysql[0].replace('VARCHAR(60)', 'VARCHAR(30)'), DDL.mysql[1]]);
    expect(failed(r)).toEqual(['customers.name']);
    expect(r.checks.find((c) => c.id === 'customers.name')?.note).toContain('30');
  });

  it('thiếu pk, identity, NOT NULL, UNIQUE', () => {
    const r = grade('mysql', ['CREATE TABLE customers (id INT, name VARCHAR(60), email VARCHAR(80), city VARCHAR(20) DEFAULT \'Hue\', score INT DEFAULT 0)', DDL.mysql[1]]);
    expect(failed(r)).toContain('customers.id');
    expect(failed(r)).toContain('customers.name');
    expect(failed(r)).toContain('customers.email');
    expect(r.checks.find((c) => c.id === 'customers.name')?.note).toContain('NOT NULL');
    expect(r.checks.find((c) => c.id === 'customers.email')?.note).toContain('UNIQUE');
    // table orders trỏ vào customers không có primary key: không dựng được, nên cũng sai.
    expect(failed(r)).toContain('table:orders');
  });

  it('DEFAULT so theo giá trị: 0 và 0.0, chữ viết khác dạng đều được; sai giá trị thì sai', () => {
    const ok = grade('mysql', [DDL.mysql[0].replace('DEFAULT 0', 'DEFAULT 0.0'), DDL.mysql[1]]);
    expect(ok.ok).toBe(true);
    const bad = grade('oracle', [DDL.oracle[0].replace("DEFAULT 'Hue'", "DEFAULT 'HCM'"), DDL.oracle[1]]);
    expect(failed(bad)).toEqual(['customers.city']);
    expect(bad.checks.find((c) => c.id === 'customers.city')?.note).toContain('Hue');
    const none = grade('mysql', [DDL.mysql[0].replace(" DEFAULT 'Hue'", ''), DDL.mysql[1]]);
    expect(failed(none)).toEqual(['customers.city']);
  });

  it('foreign key: thiếu, trỏ sai, thiếu ON DELETE', () => {
    const noFk = grade('mysql', [DDL.mysql[0], 'CREATE TABLE orders (id INT PRIMARY KEY, customer_id INT)']);
    expect(failed(noFk)).toEqual(['orders.customer_id']);
    expect(noFk.checks.find((c) => c.id === 'orders.customer_id')?.note).toContain('customers.id');
    const noDel = grade('oracle', [DDL.oracle[0], DDL.oracle[1].replace(' ON DELETE CASCADE', '')]);
    expect(failed(noDel)).toEqual(['orders.customer_id']);
    expect(noDel.checks.find((c) => c.id === 'orders.customer_id')?.note).toContain('ON DELETE CASCADE');
    const wrong = grade('mysql', [DDL.mysql[0] + '', 'CREATE TABLE orders (id INT PRIMARY KEY, customer_id INT, FOREIGN KEY (customer_id) REFERENCES customers(id) ON DELETE SET NULL)']);
    expect(failed(wrong)).toEqual(['orders.customer_id']);
  });

  it('spec không ghi onDelete thì kiểu ON DELETE nào cũng được', () => {
    const spec: SchemaSpec = { tables: [{ name: 'orders', allowExtra: true, columns: [{ name: 'customer_id', type: 'int', fk: { table: 'customers', column: 'id' }, label: 'fk' }] }] };
    expect(grade('mysql', undefined, spec).ok).toBe(true);
  });

  it('spec không ghi notNull: NULL hay NOT NULL đều được; primary key luôn kéo theo NOT NULL', () => {
    const spec: SchemaSpec = { tables: [{ name: 't', columns: [{ name: 'a', type: 'int', pk: true, notNull: true, label: 'a' }, { name: 'b', type: 'text', label: 'b' }] }] };
    for (const b of ['b VARCHAR(5)', 'b VARCHAR(5) NOT NULL']) {
      for (const d of BOTH) {
        const r = grade(d, [`CREATE TABLE t (a ${d === 'mysql' ? 'INT' : 'NUMBER(5)'} PRIMARY KEY, ${d === 'oracle' ? b.replace('VARCHAR', 'VARCHAR2') : b})`], spec);
        expect(r.ok).toBe(true);
      }
    }
  });

  it('column thừa: sai nếu allowExtra không bật, đúng nếu bật', () => {
    const steps = [DDL.mysql[0].replace('score INT DEFAULT 0', 'score INT DEFAULT 0, extra INT, more INT'), DDL.mysql[1]];
    const r = grade('mysql', steps);
    expect(failed(r)).toEqual(['customers:extra']);
    expect(r.checks.find((c) => c.id === 'customers:extra')?.note).toBe('Có column ngoài đề: extra, more.');
    const loose: SchemaSpec = { tables: SPEC.tables.map((t) => ({ ...t, allowExtra: true })) };
    expect(grade('mysql', steps, loose).ok).toBe(true);
  });

  it('primary key ghép: một check, so không phân biệt thứ tự', () => {
    const spec: SchemaSpec = {
      tables: [{ name: 'line', primaryKey: ['order_id', 'item_id'], columns: [{ name: 'order_id', type: 'int', label: 'a' }, { name: 'item_id', type: 'int', label: 'b' }] }],
    };
    const ok = grade('mysql', ['CREATE TABLE line (order_id INT, item_id INT, PRIMARY KEY (item_id, order_id))'], spec);
    expect(ok.ok).toBe(true);
    expect(ok.checks.map((c) => c.id)).toEqual(['table:line', 'line.order_id', 'line.item_id', 'line:pk', 'line:extra']);
    const one = grade('oracle', ['CREATE TABLE line (order_id NUMBER(5) PRIMARY KEY, item_id NUMBER(5))'], spec);
    expect(failed(one)).toEqual(['line:pk']);
    expect(one.checks.find((c) => c.id === 'line:pk')?.note).toContain('(order_id, item_id)');
    const none = grade('mysql', ['CREATE TABLE line (order_id INT, item_id INT)'], spec);
    expect(none.checks.find((c) => c.id === 'line:pk')?.note).toBe('Table chưa có primary key.');
  });

  it('note không dùng từ cấm', () => {
    const r = grade('mysql', ['CREATE TABLE customers (id INT, name VARCHAR(5), x INT)']);
    const text = r.checks.map((c) => c.note ?? '').join(' ');
    expect(text.length).toBeGreaterThan(20);
    expect(text).not.toMatch(/bảng|cột|hàng|dòng|khóa chính|khóa ngoại|ràng buộc|kiểu dữ liệu/i);
  });
});

describe('gradeSchema: probe', () => {
  const spec = (expect_: 'ok' | 'error', sql: string, setup?: string[]): SchemaSpec => ({
    tables: [],
    probes: [{ id: 'pr', label: 'thử', setup: setup ? { mysql: setup, oracle: setup } : undefined, sql: { mysql: sql, oracle: sql }, expect: expect_ }],
  });
  const withCheck = (d: Dialect) => build(d, [d === 'mysql' ? 'CREATE TABLE t (a INT, CHECK (a > 0))' : 'CREATE TABLE t (a NUMBER, CHECK (a > 0))']);

  for (const d of BOTH) {
    it(`${d}: CHECK chặn giá trị sai thì probe expect error đúng`, () => {
      const r = gradeSchema(withCheck(d).db(), spec('error', 'INSERT INTO t VALUES (-1)'), d);
      expect(r.ok).toBe(true);
      expect(r.checks).toEqual([{ id: 'pr', label: 'thử', ok: true, note: undefined }]);
    });

    it(`${d}: không có CHECK thì probe expect error sai, kèm note`, () => {
      const s = build(d, ['CREATE TABLE t (a ' + (d === 'mysql' ? 'INT' : 'NUMBER') + ')']);
      const r = gradeSchema(s.db(), spec('error', 'INSERT INTO t VALUES (-1)'), d);
      expect(r.ok).toBe(false);
      expect(r.checks[0].note).toContain('chặn');
    });

    it(`${d}: expect ok, và setup chạy trước`, () => {
      const s = withCheck(d);
      expect(gradeSchema(s.db(), spec('ok', 'INSERT INTO t VALUES (2)', ['INSERT INTO t VALUES (1)']), d).ok).toBe(true);
      const bad = gradeSchema(s.db(), spec('ok', 'INSERT INTO t VALUES (-2)'), d);
      expect(bad.ok).toBe(false);
      expect(bad.checks[0].note).toContain('báo lỗi');
    });
  }

  it('setup lỗi: probe sai, nói là chưa thử được', () => {
    const r = gradeSchema(withCheck('mysql').db(), spec('error', 'SELECT 1', ['INSERT INTO nothing VALUES (1)']), 'mysql');
    expect(r.ok).toBe(false);
    expect(r.checks[0].note).toContain('Chưa thử được');
  });

  it('probe chỉ viết cho một dialect thì dialect kia bỏ qua, không sinh check', () => {
    const only: SchemaSpec = { tables: [], probes: [{ id: 'p', label: 'p', sql: { oracle: 'SELECT 1 FROM DUAL' }, expect: 'ok' }] };
    expect(gradeSchema(withCheck('mysql').db(), only, 'mysql').checks).toEqual([]);
    expect(gradeSchema(withCheck('oracle').db(), only, 'oracle').checks.length).toBe(1);
  });

  it('database gốc không đổi sau probe INSERT', () => {
    const s = withCheck('mysql');
    gradeSchema(s.db(), spec('ok', 'INSERT INTO t VALUES (5)'), 'mysql');
    expect(s.db().tables[0].rows).toEqual([]);
  });
});
