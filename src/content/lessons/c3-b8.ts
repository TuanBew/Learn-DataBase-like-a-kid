const setupMysql = `CREATE TABLE departments (
  department_id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(50) NOT NULL UNIQUE,
  location VARCHAR(50)
);
CREATE TABLE employees (
  employee_id INT AUTO_INCREMENT PRIMARY KEY,
  full_name VARCHAR(100) NOT NULL,
  email VARCHAR(100) NOT NULL UNIQUE,
  hire_date DATE NOT NULL,
  salary DECIMAL(12,2) NOT NULL CHECK (salary > 0),
  department_id INT,
  manager_id INT,
  FOREIGN KEY (department_id) REFERENCES departments (department_id),
  FOREIGN KEY (manager_id) REFERENCES employees (employee_id)
);
CREATE TABLE projects (
  project_id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  start_date DATE NOT NULL,
  end_date DATE,
  budget DECIMAL(12,2) CHECK (budget >= 0),
  CHECK (end_date IS NULL OR end_date >= start_date)
);
CREATE TABLE assignments (
  employee_id INT NOT NULL,
  project_id INT NOT NULL,
  role_name VARCHAR(50) NOT NULL,
  hours_per_week INT DEFAULT 10 CHECK (hours_per_week BETWEEN 1 AND 40),
  PRIMARY KEY (employee_id, project_id),
  FOREIGN KEY (employee_id) REFERENCES employees (employee_id),
  FOREIGN KEY (project_id) REFERENCES projects (project_id)
);
CREATE TABLE leave_requests (
  request_id INT AUTO_INCREMENT PRIMARY KEY,
  employee_id INT NOT NULL,
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  reason VARCHAR(200),
  status VARCHAR(20) DEFAULT 'pending' NOT NULL,
  approved_by INT,
  CHECK (end_date >= start_date),
  CHECK (status IN ('pending', 'approved', 'rejected')),
  FOREIGN KEY (employee_id) REFERENCES employees (employee_id),
  FOREIGN KEY (approved_by) REFERENCES employees (employee_id)
);`;

const setupOracle = `CREATE TABLE departments (
  department_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR2(50) NOT NULL UNIQUE,
  location VARCHAR2(50)
);
CREATE TABLE employees (
  employee_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR2(100) NOT NULL,
  email VARCHAR2(100) NOT NULL UNIQUE,
  hire_date DATE NOT NULL,
  salary NUMBER(12,2) NOT NULL CHECK (salary > 0),
  department_id NUMBER,
  manager_id NUMBER,
  FOREIGN KEY (department_id) REFERENCES departments (department_id),
  FOREIGN KEY (manager_id) REFERENCES employees (employee_id)
);
CREATE TABLE projects (
  project_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR2(100) NOT NULL,
  start_date DATE NOT NULL,
  end_date DATE,
  budget NUMBER(12,2) CHECK (budget >= 0),
  CHECK (end_date IS NULL OR end_date >= start_date)
);
CREATE TABLE assignments (
  employee_id NUMBER NOT NULL,
  project_id NUMBER NOT NULL,
  role_name VARCHAR2(50) NOT NULL,
  hours_per_week NUMBER DEFAULT 10 CHECK (hours_per_week BETWEEN 1 AND 40),
  PRIMARY KEY (employee_id, project_id),
  FOREIGN KEY (employee_id) REFERENCES employees (employee_id),
  FOREIGN KEY (project_id) REFERENCES projects (project_id)
);
CREATE TABLE leave_requests (
  request_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id NUMBER NOT NULL,
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  reason VARCHAR2(200),
  status VARCHAR2(20) DEFAULT 'pending' NOT NULL,
  approved_by NUMBER,
  CHECK (end_date >= start_date),
  CHECK (status IN ('pending', 'approved', 'rejected')),
  FOREIGN KEY (employee_id) REFERENCES employees (employee_id),
  FOREIGN KEY (approved_by) REFERENCES employees (employee_id)
);`;

